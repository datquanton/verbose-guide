#!/usr/bin/env python3
"""Builds flow.js for the portfolio consultant: order-flow and longer momentum figures per ticker.

Input : JSON files as returned by FiinQuantX Fetch_Trading_Data with fields close, value, fn, bu, sd
        (daily, ~260 sessions) for the tickers in market.js.
Output: flow.js -> window.PM_FLOW = {...}

    python3 build_flow.py flows1.json flows2.json > flow.js

  fnet   foreign net buying over the last 60 sessions as a share of traded value (fn and value are both VND)
  obi    active buy volume minus active sell volume over (buy + sell), last 60 sessions
  r6m    price change from the first session on or after (as-of minus 182 days), %
  r12_1  price change from the first session in the file to 21 sessions before the last, %  (12-month momentum skipping the last month)
The current unfinished session is dropped. Some sessions are missing from this feed, so returns are taken between dates,
never by counting rows, and these files are not used for volatility or correlation.
"""
import json, sys, datetime

def main(paths):
    by = {}
    for p in paths:
        for r in json.load(open(p, encoding='utf-8'))['data']['records']:
            if r.get('close') is None or not r['timestamp'].endswith('00:00'): continue   # drop the open session
            by.setdefault(r['ticker'], []).append(r)
    out = {}; asof = None
    for t, rows in by.items():
        rows.sort(key=lambda r: r['timestamp'])
        if t == 'VNINDEX' or len(rows) < 30: 
            if t == 'VNINDEX': asof = rows[-1]['timestamp'][:10]
            continue
        last = rows[-60:]
        val = sum(r.get('value') or 0 for r in last); fn = sum(r.get('fn') or 0 for r in last)
        bu = sum(r.get('bu') or 0 for r in last); sd = sum(r.get('sd') or 0 for r in last)
        d1 = datetime.date.fromisoformat(rows[-1]['timestamp'][:10]); cut = (d1 - datetime.timedelta(days=182)).isoformat()
        span = (d1 - datetime.date.fromisoformat(rows[0]['timestamp'][:10])).days
        six = next((r for r in rows if r['timestamp'][:10] >= cut), None)
        o = {'n': len(last),
             'fnet': round(fn / val, 4) if val else None,
             'obi': round((bu - sd) / (bu + sd), 4) if bu + sd else None,
             'r6m': round((rows[-1]['close'] / six['close'] - 1) * 100, 1) if six and span >= 170 else None,
             'r12_1': round((rows[-22]['close'] / rows[0]['close'] - 1) * 100, 1) if span >= 330 and len(rows) > 60 else None}
        out[t] = o
    sys.stdout.write('/* Generated by build_flow.py from FiinQuantX daily trading data; do not edit by hand. */\n')
    sys.stdout.write('window.PM_FLOW = ' + json.dumps({'asof': asof, 't': out}, separators=(',', ':')) + ';\n')

if __name__ == '__main__':
    main(sys.argv[1:])
